"""Build an episode of the vertical flat cut: line timings, captions, frames, soundtrack, final mp4.

Usage: python3 build.py <episode_dir> <out.mp4> [--from SECONDS] [--to SECONDS] [--workers N] [--tmp DIR]
<episode_dir>/episode.json: {"voice": ..., "alignment": ..., "end": ..., "voice_end": ..., "keywords": ...}
(paths relative to the repository). Shot files are <episode_dir>/scene*.js; the soundtrack comes from
<episode_dir>/sound.py, called as: sound.py <voice> <out.wav> <end>.
"""
import argparse
import concurrent.futures
import glob
import json
import os
import subprocess
import sys

import numpy as np

ENGINE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(ENGINE))
FPS, FW, FH = 30, 1080, 1920


def write_timing(alignment, voice, out):
    """LINES[n] = [start, end] of script line n, S/E/C helpers, and the voice loudness for lip movement."""
    lines = json.load(open(alignment, encoding='utf-8'))['lines']
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', voice, '-f', 's16le', '-ac', '1', '-ar', '16000', '-'],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, '<i2').astype(np.float64) / 32768
    hop = 16000 // 50
    n = len(x) // hop
    rms = np.sqrt(np.mean(x[: n * hop].reshape(n, hop) ** 2, axis=1))
    v = np.clip(rms / np.percentile(rms, 95), 0, 1)
    rows = ',\n'.join(f"  [{l['start']:.3f}, {l['end']:.3f}]" for l in lines)
    with open(out, 'w') as f:
        f.write('// Generated by engine/build.py: LINES[n] = [start, end] of script line n.\n'
                "'use strict';\nconst LINES = [null,\n" + rows + '\n];\n'
                '// S(n), E(n): start and end of line n; C(n): cut point in the pause before line n.\n'
                'const S = n => LINES[n][0], E = n => LINES[n][1], C = n => (LINES[n - 1][1] + LINES[n][0]) / 2;\n'
                '// VENV[k]: voice loudness 0..1 at time k / 50 s; MOUTH(t): how open a speaking mouth is.\n'
                'const VENV = [' + ','.join(f'{a:.2f}'.rstrip('0').rstrip('.') or '0' for a in v) + '];\n'
                'const MOUTH = t => { const k = t * 50, i = Math.floor(k); return i < 0 || i + 1 >= VENV.length ? 0 : VENV[i] + (VENV[i + 1] - VENV[i]) * (k - i); };\n')
        if all('words' in l for l in lines):
            # WORDS[n] = [[word, start, end], ...]; Wd(n, prefix, k) = start of the k-th (first by default) word of line n beginning with prefix
            f.write('const WORDS = [null,\n' + ',\n'.join('  ' + json.dumps(l['words'], ensure_ascii=False) for l in lines) + '\n];\n'
                    "const Wd = (n, p, k = 0) => { const w = WORDS[n].filter(w => w[0].toLowerCase().replace(/[^а-яё0-9-]/g, '').startsWith(p))[k]; return w ? w[1] : S(n); };\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('episode')
    ap.add_argument('out')
    ap.add_argument('--from', dest='t0', type=float, default=0.0)
    ap.add_argument('--to', dest='t1', type=float)
    ap.add_argument('--workers', type=int, default=4)
    ap.add_argument('--tmp', default='/tmp/episode_build')
    a = ap.parse_args()
    ep = os.path.abspath(a.episode)
    cfg = json.load(open(os.path.join(ep, 'episode.json'), encoding='utf-8'))
    voice, alignment = os.path.join(REPO, cfg['voice']), os.path.join(REPO, cfg['alignment'])
    end, voice_end = cfg['end'], cfg.get('voice_end', cfg['end'])
    t1 = min(a.t1 or end, end)
    os.makedirs(a.tmp, exist_ok=True)
    write_timing(alignment, voice, os.path.join(ep, 'timing.js'))
    cap = [sys.executable, os.path.join(ENGINE, 'captions.py'), alignment, os.path.join(ep, 'captions.js'), str(voice_end)]
    if cfg.get('keywords'):
        cap.append(os.path.join(REPO, cfg['keywords']))
    subprocess.run(cap, check=True)
    shots = [os.path.join(ENGINE, 'flat.js'), os.path.join(ep, 'timing.js'), os.path.join(ep, 'captions.js')] + \
        sorted(glob.glob(os.path.join(ep, 'scene*.js')))
    f0, f1 = int(round(a.t0 * FPS)), int(round(t1 * FPS))
    n = a.workers * 2
    cuts = [f0 + (f1 - f0) * i // n for i in range(n + 1)]

    def render(i):
        out = os.path.join(a.tmp, f'seg{i:02}.mp4')
        subprocess.run(['node', os.path.join(ENGINE, 'render.js'), '--shots=' + ','.join(shots), f'--fps={FPS}', f'--w={FW}', f'--h={FH}',
                        f'--f0={cuts[i]}', f'--f1={cuts[i + 1]}', f'--out={out}'], check=True)
        return out

    with concurrent.futures.ThreadPoolExecutor(a.workers) as ex:
        segs = list(ex.map(render, range(n)))
    lst = os.path.join(a.tmp, 'segs.txt')
    open(lst, 'w').write(''.join(f"file '{s}'\n" for s in segs))
    raw = os.path.join(a.tmp, 'raw.mp4')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'concat', '-safe', '0', '-i', lst, '-c', 'copy', raw], check=True)
    wav = os.path.join(a.tmp, 'sound.wav')
    subprocess.run([sys.executable, os.path.join(ep, 'sound.py'), voice, wav, str(end)], check=True)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', raw, '-ss', f'{a.t0:.3f}', '-t', f'{t1 - a.t0:.3f}', '-i', wav,
                    '-af', 'loudnorm=I=-16:TP=-1.5:LRA=11,aresample=48000',
                    '-c:v', 'libx264', '-preset', 'slow', '-crf', '20', '-maxrate', '2.6M', '-bufsize', '5.2M', '-pix_fmt', 'yuv420p',
                    '-c:a', 'aac', '-b:a', '192k', '-movflags', '+faststart', '-shortest', a.out], check=True)
    print(a.out)


if __name__ == '__main__':
    main()
